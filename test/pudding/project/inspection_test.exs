defmodule Pudding.Project.InspectionTest do
  use ExUnit.Case, async: true
  alias Pudding.Project.{Capture, Inspection, Manifest}

  defp inventory(build, output),
    do: Inspection.inventory(build, output, "/workspace/consumer/_build")

  @tag :tmp_dir
  test "comparison includes filesystem types, modes and empty directories", %{tmp_dir: dir} do
    build = dir <> "/build"
    File.mkdir_p!(build)
    File.ln_s!("/workspace/consumer/priv", build <> "/priv")
    first = inventory(build, dir <> "/first")
    assert Enum.any?(first, &(&1["type"] == "symlink"))
    File.rm!(build <> "/priv")
    File.write!(build <> "/priv", "/workspace/consumer/priv")
    inventory(build, dir <> "/second")

    {a, b} =
      {File.read!(dir <> "/first/build-inventory.json"),
       File.read!(dir <> "/second/build-inventory.json")}

    assert a != b

    refute Capture.compare(%{"files" => %{"build-inventory.json" => Manifest.digest(a)}}, %{
             "files" => %{"build-inventory.json" => Manifest.digest(b)}
           })["equal"]

    File.chmod!(build <> "/priv", 0o755)
    File.mkdir!(build <> "/empty")
    changed = inventory(build, dir <> "/third")

    assert Enum.any?(
             changed,
             &(&1["type"] == "directory" and String.ends_with?(&1["name"], "/empty"))
           )

    assert Enum.any?(changed, &(&1["mode"] == 0o755 and &1["type"] == "regular"))
  end

  @tag :tmp_dir
  test "external resources bind the generated mount bytes, not the hidden source", %{tmp_dir: dir} do
    File.mkdir_p!(dir <> "/work/generated-1")
    File.write!(dir <> "/work/generated-1/policy", "generated bytes")
    req = %{"project" => "consumer", "writable_paths" => ["consumer/generated/data"]}
    path = "/workspace/consumer/generated/data/policy"

    assert %{"path" => ^path, "sha256" => hash, "size" => 15} =
             Inspection.resource!(req, dir <> "/work/build", path)

    assert hash == Manifest.digest("generated bytes")
    File.rm!(dir <> "/work/generated-1/policy")
    File.ln_s!(dir <> "/secret", dir <> "/work/generated-1/policy")

    assert_raise ArgumentError, ~r/undeclared external resource/, fn ->
      Inspection.resource!(req, dir <> "/work/build", path)
    end

    assert_raise ArgumentError, ~r/undeclared external resource/, fn ->
      Inspection.resource!(req, dir <> "/work/build", "/etc/passwd")
    end
  end

  @tag :tmp_dir
  test "unexpected links and excessive directory depth fail before callbacks", %{tmp_dir: dir} do
    File.mkdir_p!(dir <> "/links")
    File.ln_s!("/etc/passwd", dir <> "/links/priv")

    assert_raise ArgumentError, ~r/unsafe build link/, fn ->
      inventory(dir <> "/links", dir <> "/out")
    end

    deep = Enum.reduce(1..66, dir <> "/deep", fn _, path -> path <> "/d" end)
    File.mkdir_p!(deep)

    assert_raise ArgumentError, ~r/depth limit/, fn ->
      inventory(dir <> "/deep", dir <> "/out2")
    end
  end
end
